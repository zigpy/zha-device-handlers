"""Regenerate the mypy disable_error_code overrides in pyproject.toml.

Usage:
    python -m tools.regenerate_mypy_ignores

Errors are grouped per vendor package (`zhaquirks.<vendor>.*`), plus one entry
for each top-level module (`zhaquirks`, `zhaquirks.const`, ...). A quirk added
to an existing vendor package inherits that package's suppressions; a module in
a package without an entry is checked in full.
"""

from collections import defaultdict
from pathlib import Path
import re

from mypy import api as mypy_api

START_MARKER = "# Autogenerated mypy overrides: start"
END_MARKER = "# Autogenerated mypy overrides: end"

PACKAGE = "zhaquirks"

# The base type-checking strictness enforced, expressed as CLI flags so the run
# is independent of the overrides we are about to regenerate.
# Keep in sync with the non-override settings in [tool.mypy] in pyproject.toml.
MYPY_FLAGS = [
    PACKAGE,
    "--config-file=/dev/null",
    "--python-version=3.12",
    "--strict",
    "--ignore-missing-imports",
    "--follow-imports=silent",
    "--warn-unreachable",
    "--no-error-summary",
]


def run_mypy() -> list[str]:
    """Run mypy with no error codes disabled and capture output."""
    stdout, stderr, _ = mypy_api.run(MYPY_FLAGS)
    return stdout.splitlines() + stderr.splitlines()


def module_group(filepath: str) -> str:
    """Map a source file to the override entry that covers it."""
    parts = Path(filepath).with_suffix("").parts

    # `zhaquirks/__init__.py` and top-level modules like `zhaquirks/const.py`
    if len(parts) == 2:
        return PACKAGE if parts[1] == "__init__" else ".".join(parts)

    # Everything in a vendor package, including its `__init__.py`
    return f"{parts[0]}.{parts[1]}.*"


def parse_errors(lines: list[str]) -> dict[str, dict[str, int]]:
    """Parse mypy output into {module group: {error_code: count}}."""
    errors_by_module: dict[str, dict[str, int]] = defaultdict(lambda: defaultdict(int))

    for line in lines:
        match = re.match(r"^([^:]+\.pyi?):.* \[([a-z-]+)\]$", line.strip())
        if match:
            filepath, error_code = match.groups()
            errors_by_module[module_group(filepath)][error_code] += 1

    return dict(errors_by_module)


def format_override(module: str, codes: dict[str, int]) -> str:
    """Format a single [[tool.mypy.overrides]] section."""
    lines = [
        "[[tool.mypy.overrides]]",
        f'module = "{module}"',
        "disable_error_code = [",
    ]
    for code in sorted(codes.keys()):
        lines.append(f'    "{code}",  # {codes[code]}')  # noqa: PERF401
    lines.append("]")
    return "\n".join(lines)


def generate_overrides(errors_by_module: dict[str, dict[str, int]]) -> str:
    """Generate all override sections, sorted easiest-to-fix first."""
    # Sort by (total error count, module name) so easiest fixes are at the top
    sorted_modules = sorted(
        errors_by_module.items(), key=lambda x: (sum(x[1].values()), x[0])
    )

    total = sum(sum(codes.values()) for codes in errors_by_module.values())
    header = f"# Total ignored errors: {total} across {len(errors_by_module)} entries"

    sections = [format_override(module, codes) for module, codes in sorted_modules]
    return header + "\n" + "\n\n".join(sections)


def main() -> None:
    """Entry point."""
    pyproject_path = Path("pyproject.toml")
    content = pyproject_path.read_text()

    lines = run_mypy()
    errors_by_module = parse_errors(lines)
    overrides_content = generate_overrides(errors_by_module)

    # Replace content between markers
    pattern = re.compile(
        rf"({re.escape(START_MARKER)})\n(?:.*?\n)?({re.escape(END_MARKER)})",
        re.DOTALL,
    )
    new_content = pattern.sub(rf"\1\n{overrides_content}\n\2", content)

    if new_content != content:
        pyproject_path.write_text(new_content)


if __name__ == "__main__":
    main()
